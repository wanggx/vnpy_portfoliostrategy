# -*- coding: utf-8 -*-
"""策略是怎么跑起来的 —— 运行流程

只讲**运行时序**：框架在什么时候调什么、每一步在干什么、
什么条件下才真的动手、以及看日志怎么判断"跑对了没有"。

不列函数清单、不重复算法口径（要看算法细节看 qmt/README.md）。
框架回调契约见 doc/qmt_callbacks_skeleton.py。

一句话：**init 里那一行 run_time 让策略从"被加载的代码"变成"在跑的策略"；
之后每 3 秒 main_loop 跑一轮，一轮里先"准备今天"、再"交易"。**
"""


# =============================================================================
# 一、总览：谁在什么时候被调
# =============================================================================
#
#  时间          谁被调              它在干什么
#  ───────────────────────────────────────────────────────────────────────────
#  启动瞬间      init(C)            绑定账号 + 注册 3 秒心跳  ← 从这里"跑起来"
#                after_init(C)       取交易日历（init 里取不到）
#                handlebar(C)        空实现（定时器型必须留空）
#
#  08:40~09:20   main_loop(C)       每 3 秒一轮：选股分片推进，每轮 200 只
#                                    （全市场约 5000 只 -> 约 25 轮跑完）
#
#  09:15 起      main_loop(C)       同一轮里：情绪开始采样（满 30 秒采一次）
#                main_loop(C)       同一轮里：票池刷新一次（同步持仓/订阅tick/算布林）
#
#  09:30 起      main_loop(C)       从这一轮开始才会下单
#  14:57 后      main_loop(C)       每轮走到"时段闸门"就 return
#  15:00         情绪停止采样
#
#  盘中随时      order_callback     委托推送（仅实盘模式）
#                deal_callback      成交推送（仅实盘模式）
#                orderError_callback / position_callback / account_callback
#
#  停止          stop(C)            交易连接已断，只收尾


# =============================================================================
# 二、启动的那一刻
# =============================================================================
# 框架先做（我们管不着）：
#   加载模型 -> exec 源码 -> 把 account / accountType / passorder / cancel /
#   get_trade_detail_data ... 注入到本模块全局 -> 然后调 init(C)

def init(C):
    # ① 记"今天"。后面所有"今天"的判断、日切比较全靠它
    G.day = _today()

    # ② 委托号序号随机起头，避免重启后 uid 撞车
    G.seq = int(time.time()) % 100000

    # ③ 账号：界面没选账号时注入的是空串，这里只告警、不阻断
    if not account:
        log('警告：未取到 account（策略交易界面需选定账号），下单将失败')

    # ④ ★关键：不调 set_account，order/deal 等实时回调不会生效
    C.set_account(account)

    # ⑤ ★关键：注册心跳（startTime 设成过去 -> 立刻生效）
    #    手册："部分周期下定时器函数在第一次运行之前会先等待一个 period"
    #    => 首轮 main_loop 大约在启动 3 秒后才来，别指望 init 后立刻跑一次
    C.run_time('main_loop', '3nSecond', '2019-01-01 09:00:00')

    # ⑥ 打版本指纹，用来确认 QMT 里跑的是不是最新那份
    #    log('策略初始化完成 build=%s acct=%s type=%s 票池板块=%s 单行业=%s' % ...)


def after_init(C):
    # init 里 C.get_trading_dates 取不到数据，必须放这里。
    # 手册："系统会在 init 函数执行完后和**执行 handlebar 之前**调用 after_init"
    G.trade_dates = C.get_trading_dates('000001.SH', FIXED_DATES[0], _today(), -1, '1d')
    G.is_trade_day = G.day in G.trade_dates

    # 降级：日历取不到 -> 不判非交易日（否则策略整天不动）
    if not G.trade_dates:
        G.is_trade_day = True


def handlebar(C):
    # 必须存在（手册："PY策略必须有该函数"），但必须留空。
    # 一旦在这里写逻辑，它会被"每根历史 K 线 + 每个 tick"各驱动一次 —— 主循环翻倍跑。
    return


# =============================================================================
# 三、之后每 3 秒：main_loop 一轮做什么（核心）
# =============================================================================
# 一轮 11 步，顺序不能乱：第 1~5 步是"准备今天"，第 6~11 步才是"交易"。

def main_loop(C):

    # ─────────────────────────────────────────────────────────────────────
    # 第 1 步：日切 —— 全策略唯一会"清状态"的地方
    # ─────────────────────────────────────────────────────────────────────
    today = _today()
    if G.day != today:
        G.day = today
        _reset_daily()          # 清当日状态；保留要跨日的开仓价/最大收益/冷却
        G.is_trade_day = (today in G.trade_dates) if G.trade_dates else True
        log('日切：%s %s' % (today, '交易日' if G.is_trade_day else '非交易日'))

    if not G.is_trade_day:
        return                  # 非交易日：后面 10 步全不做

    # ─────────────────────────────────────────────────────────────────────
    # 第 2 步：选股推进（08:40~09:20 每轮推一批；盘中启动也会补跑一次）
    # ─────────────────────────────────────────────────────────────────────
    _maybe_screen(C)
    # 每轮只做两件事之一：
    #   · 判断要不要"启动一轮选股"（时段外 + 票池为空 + ALLOW_LATE_SCREEN -> 补跑）
    #   · 推进一批 200 只；游标到底就收尾：排序 -> 排 ST -> 前 100 名写 G.target_symbols
    # 本轮恰好跑完时会设 G.pool_date = ''
    #   -> 让下面第 4 步重新走一遍 _refresh_pool（订阅 tick / 算布林 / 同步持仓）
    # 日志：选股启动 / 选股打分完成 / 选股完成：N 只入池

    # ─────────────────────────────────────────────────────────────────────
    # 第 3 步：情绪采样（09:15 起，满 30 秒采一次）
    # ─────────────────────────────────────────────────────────────────────
    _maybe_sample_sentiment(C)
    # 每天首次进这里：先重建基础数据（全市场代码表 / ST 集合 / 131 个板块成员缓存）
    # 之后按 30 秒节流 -> 一次 get_full_tick 取全市场 + 3 个指数
    #                 -> 算 宽度分 / 指数分 / 行业分 -> 加权合成 -> 写 G.sent_*
    # 情绪每 30 秒更新一次，而买卖判断每 3 秒读一次 —— 读到的最多可能是 30 秒前的分，
    # 所以"可用"判定给了 90 秒宽限（允许连续 2 次采样失败）。

    # ─────────────────────────────────────────────────────────────────────
    # 第 4 步：盘前刷新票池（09:15 之后，一天一次）
    # ─────────────────────────────────────────────────────────────────────
    clock = _clock()
    if clock >= REFRESH_TIME and G.pool_date != G.day:
        _refresh_pool(C)
        # 三件事：
        #   ① 同步券商持仓 -> 本地没有开仓价的用 m_dOpenPrice 兜底（策略重启后的救命路径）
        #   ② 订阅 tick（票池 ∪ 持仓）
        #   ③ 算布林上轨（只算"今天可卖出"的持仓）
        # 日志：tick 订阅 n/m 只 / 布林上轨刷新 n/m 只 / 票池刷新完成：池内 N 只...

    # ─────────────────────────────────────────────────────────────────────
    # 第 5 步：交易时段闸门（09:30~14:57）—— 闸门之前的工作 09:30 前就在跑了
    # ─────────────────────────────────────────────────────────────────────
    if clock < MARKET_OPEN_TIME or clock > TRADE_END_TIME:
        return

    # ─────────────────────────────────────────────────────────────────────
    # 第 6 步：查账户现状（每次都现查，不做本地缓存）
    # ─────────────────────────────────────────────────────────────────────
    positions = _pos_map()                       # 持仓（只返回有仓的行）
    G.deployed_cash = _deployed_cash(positions)  # 持仓成本 + 在途买单
    G.available_cash = _available_cash()         # 账户可用资金

    # ─────────────────────────────────────────────────────────────────────
    # 第 7 步：委托对账 —— 实时回调的兜底
    # ─────────────────────────────────────────────────────────────────────
    _sync_orders()
    # 按 m_strRemark == userOrderId 把柜台委托关联回 G.pending，补 sysid / 成交量 / 状态
    # 60 秒还拿不到委托号 -> 标 'lost' 告警（可能未被柜台受理）
    # ★ 模拟信号模式没有任何实时回调，这一步是唯一的状态来源

    # ─────────────────────────────────────────────────────────────────────
    # 第 8 步：卖单超时处理
    # ─────────────────────────────────────────────────────────────────────
    _check_sell_timeout(C)      # 卖单挂满 5 分钟未全成交 -> 告警 + 撤单（不重发）

    # ─────────────────────────────────────────────────────────────────────
    # 第 9 步：取价（票池 ∪ 持仓）
    # ─────────────────────────────────────────────────────────────────────
    _poll_pool(C, positions)
    # ★ 必须并上持仓：持仓掉出票池后如果没行情，卖出链永远看不到价格

    # ─────────────────────────────────────────────────────────────────────
    # 第 10 步：卖出链（先卖）
    # ─────────────────────────────────────────────────────────────────────
    _trade_positions(C, positions)

    # ─────────────────────────────────────────────────────────────────────
    # 第 11 步：买入链（后买）
    # ─────────────────────────────────────────────────────────────────────
    _trade_buys(C, positions)


# =============================================================================
# 四、一笔买入是怎么发生的（端到端）
# =============================================================================
#  ① 09:15 票池刷新后，票池里的标的开始有"窗口样本"
#     —— tick 回调（subscribe_quote）和每 3 秒的 _poll_pool 都会调 _on_price，
#        对"在票池内且还没持仓"的标的，把 (时间, 价格) 追加进 G.window[code]
#
#  ② 每 3 秒，第 11 步遍历票池，逐个算：
#       gain = (现价 - 窗口内最低价) / 窗口内最低价      # 窗口 300 秒
#       窗口样本跨度不足 180 秒 -> 不算
#       gain < 3% -> 退化为"昨收涨幅"，还不到 3% 就放弃
#
#  ③ 过了涨幅门槛后，三道闸门依次过：
#       大盘闸门：大盘 偏弱/极弱 -> 一票否决，任何标的都不买（告警一次就退出）
#       行业闸门：行业情绪评级不够 -> 当日该标的不再重试（记入 G.entered）
#       资金闸门：已占用 + 这一笔 > MAX_CASH，或 > 账户可用资金 -> 跳过（告警一次）
#
#  ④ 下单：passorder(opType, 1101, account, code, 11, 现价+0.05, 500,
#                    'NEARMA', 2, uid, C)
#     uid = 'BUY_<YYYYMMDD>_<序号>'，同时登记 G.pending[uid] = {status: 'alive', ...}
#     —— 本地先乐观登记，后面靠回调/对账来修正
#
#  ⑤ 两个来源把状态改回来：
#       实盘模式：deal_callback 成交推送 -> _handle_deal
#                 -> 若"成交后持仓量 <= 本次成交量"（首次建仓）-> 记开仓价 = 成交价
#       任意模式：第 7 步 _sync_orders 轮询对账，按 m_strRemark 找回委托
#
#  ★ 防重复：G.entered 记"当日已开仓"，同一标的当天只买一次；
#            下单前还检查"该标的是否已有在途委托"。


# =============================================================================
# 五、一笔卖出是怎么发生的（端到端）
# =============================================================================
#  ① 第 10 步遍历"账户里所有有可卖量的持仓"（不是只遍历票池！）
#       可卖量 = T+1 下的 m_nCanUseVolume
#     ★ 所以票池外被手工买入/别的策略持有的标的，也会被本策略卖出
#
#  ② 必须先有价格（G.last）—— 所以第 9 步取价要覆盖持仓
#
#  ③ 兜底开仓价：本地 G.entry_prices 没有这个标的时，用券商成本价 m_dOpenPrice
#     （策略重启后唯一的止盈基准来源；只在缺失时写，不反向覆盖）
#     然后刷新"开仓后最大收益率"—— 回撤/保底线都依赖它
#
#  ④ _sell_signal 按固定优先级判 7 条，命中即返回：
#       情绪离场 / 止损(宽档4%或常规2%) / 止盈清仓20% / 减半10% / 回撤10%
#       / 跌破保底 / 布林上轨
#     中间那条"减半"没命中还会导致"这一轮不卖"，等下一轮再看
#
#  ⑤ 下单：价格用 现价-0.05（卖出减价），数量和上面算出来的一致
#     下单前同样检查"该标的是否已有在途委托"
#
#  ⑥ 成交 -> deal_callback：登记禁买冷却（亏损离场 -> 冷却 2 个自然日）
#     若成交后已无持仓 -> 清掉 entry_prices / max_profit_pct / entered
#
#  ⑦ 挂太久没成交 -> 第 8 步 _check_sell_timeout 撤单（不重发；条件仍成立下一轮会重新下单）


# =============================================================================
# 六、状态是怎么活下来的（日切 / 跨日 / 重启）
# =============================================================================
#
# 日切时 _reset_daily() 清掉（都是"当日"概念）：
#   entered / window / boll_up / pending / last / screen / 情绪全部 / 告警闸门 / cash_short
#   （另外顺手清理 cooldown_dates 里已过期的条目）
#
# 跨日保留：
#   entry_prices    开仓价（持仓还没卖，止盈基准不能丢）
#   max_profit_pct  开仓后最大收益（回撤/保底依赖它）
#   cooldown_dates  禁买截止日（本来就是跨日的）
#   target_symbols  票池（保留到明天新选股结果覆盖它）
#   trade_dates / 板块缓存 / 全市场代码表
#
# 策略重启（进程重来）：
#   上面全部丢失 -> 靠两条路恢复：
#     ① 开仓价：_sync_entry_from_broker 用券商 m_dOpenPrice 兜底
#     ② 最大收益：从 0 重算（所以回撤/保底保护会暂时放宽）
#     ③ 禁买冷却：全丢（当天一律禁买这条天然还成立，之后的锁定期没了）
#   => 日内重启策略要人工留意持仓标的的止盈基准


# =============================================================================
# 七、冷启动 / 异常路径
# =============================================================================
#
# 盘中才启动策略（比如 11:30 打开）：
#   已过 08:40~09:20 选股时段，且票池为空 -> ALLOW_LATE_SCREEN 补跑一次选股
#   补跑要占共享线程约 1~2 分钟（期间界面会有点卡）
#   跑完后 G.pool_date = '' -> 下一轮自动走"票池刷新"（订阅/布林/同步持仓）
#
# 票池为空：
#   _refresh_pool 打"票池为空（选股可能未完成），本轮不交易"，tick 订阅 0/0
#   情绪照常算，但第 10/11 步没东西可交易
#
# 界面没选账号：
#   account 是空串 -> 告警；get_trade_detail_data 查不到持仓/资金
#   -> 持仓空、可用资金 0 -> 买入被资金闸门拦住；卖出也无从下手
#
# 交易日历取不到：
#   G.is_trade_day 降级为 True（宁可跑，也不要整天不动）
#
# 情绪不可用：
#   大盘评级 = '不可用' -> 大盘闸门不生效（不否决），
#   但行业闸门走的是严格分支（要求行业 偏强/极强）-> 实际很难买入
#
# 一个板块成员都没取到：
#   没有"股票 -> 行业"映射 -> _sector_buyable 返回"未达准入"
#   -> **全部买入被拦截**（日志会打告警）


# =============================================================================
# 八、启动自检清单（照着日志逐条对）
# =============================================================================
#
#  1. [NEARMA] 策略初始化完成 build=xxxxxxxx acct=<账号> type=STOCK 票池板块=沪深A股
#        -> build 值要和 qmt/near_ma_surge_qmt.py 里的 BUILD_ID 一致（确认粘的是最新版）
#        -> acct 不能为空（空的说明界面没选账号）
#
#  2. [NEARMA] 交易日历 1081 个，今天 20261014 是交易日
#        -> 说明 after_init 被调用了、日历取到了
#
#  3. [NEARMA] 板块成员缓存：131 个板块，覆盖率 4949 只标的（耗时 0.01s）
#        -> 行业映射建好了；若打"警告：一个板块成员都没取到"，买入会全被拦
#
#  4. [NEARMA] 选股启动：板块"沪深A股" N 只，T=..., 数据区间 ..., 每轮 200 只
#
#  5. [NEARMA] 选股打分完成：x/y 只接近至少一条均线，日线不足剔除 a，未腰斩剔除 b
#
#  6. [NEARMA] 选股完成：N 只入池，最高分 x，最低分 y，T=...
#
#  7. [NEARMA] tick 订阅：n/m 只          <- 订阅数超限会 break，不影响交易
#  8. [NEARMA] 布林上轨刷新 n/m 只
#  9. [NEARMA] 票池刷新完成：池内 N 只，持仓 M 只，冷却中 K 只，tick 订阅 S 只
#
# 10. 之后每 3 秒（VERBOSE_TICK = True 时）：
#       [NEARMA] 轮询 HH:MM:SS 池内 N 持仓 M 在途 P 大盘 评级 X 分
#
# 11. 有信号才会出现：
#       快速拉升买入 xxx(xx) 窗口涨幅 4.00% 买入价格 10.55 数量 500 大盘 ... 行业 ...
#       卖出信号 xxx(xx) <原因> 卖出价格 ... 当前收益 ... 最大收益 ... 大盘 ... 行业 ...


# =============================================================================
# 九、最后一句话
# =============================================================================
#
#   3 秒一次的心跳，每轮就三件事：
#     ① 收尾昨天（日切）
#     ② 准备今天（选股 / 情绪 / 票池刷新）
#     ③ 交易（先卖后买）
#
#   实时回调（order/deal）只是"加速知道结果"；就算一个回调都不来，
#   第 7 步的轮询对账也能把状态补回来 —— 这是能在模拟信号模式下跑通的原因。
